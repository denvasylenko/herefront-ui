// Builds the tokens: tokens/*.json → dist/
//   tokens.css     --hf-* variables: base measures on :root, one block per theme (light, dark, forced scheme)
//   compat.css     the old names the products read today (--bg, --muted, --radius…) as aliases of --hf-*
//   ios-tokens.css the --ios-* measures for the sites (no colours of a palette; inlined into every page)
//   tokens.json    flat values for Python and the bot images: {base: {name: value}, themes: {id: {scheme, light, dark}}}
// No dependencies: node build/build.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'))
const HEAD = (what) => `/* herefront-ui ${what} — generated by build/build.mjs from tokens/*.json. Do not edit here: change the JSON and rebuild. */\n`
export const DEFAULT_THEME = 'dashboard'

// base.json → [{name: 'radius-2', value, legacy}]
export function flatten(tree, path = []) {
  const out = []
  for (const [k, v] of Object.entries(tree)) {
    if (k.startsWith('$')) continue
    if (v && typeof v === 'object' && '$value' in v) out.push({ name: [...path, k].join('-'), value: String(v.$value), legacy: v.$legacy })
    else if (v && typeof v === 'object') out.push(...flatten(v, [...path, k]))
  }
  return out
}

export function load() {
  const base = flatten(read('tokens/base.json'))
  const themes = {}
  for (const f of readdirSync(join(ROOT, 'tokens/themes')).filter((f) => f.endsWith('.json')).sort()) {
    const t = read('tokens/themes/' + f)
    themes[f.replace(/\.json$/, '')] = { scheme: t.$scheme || 'auto', light: t.light || {}, dark: t.dark || {} }
  }
  if (!themes[DEFAULT_THEME]) throw new Error('no default theme ' + DEFAULT_THEME)
  return { base, themes, compat: read('tokens/compat.json') }
}

const decl = (obj) => Object.entries(obj).map(([k, v]) => `  --hf-${k}: ${v};`).join('\n')
const block = (sel, body) => `${sel} {\n${body}\n}\n`

// the default theme sits on :root with the same weight as before (0,1,0), so a theme the dashboard injects later
// (kit/theme.js applyTheme → <style> :root {…}) still wins by order, as it did over the old tokens.css
export function tokensCss({ base, themes }) {
  let css = HEAD('tokens') + block(':root', base.map((t) => `  --hf-${t.name}: ${t.value};`).join('\n'))
  const ids = [DEFAULT_THEME, ...Object.keys(themes).filter((id) => id !== DEFAULT_THEME)]
  for (const id of ids) {
    const t = themes[id], is = `[data-hf-theme="${id}"]`
    const own = id === DEFAULT_THEME ? `:root, ${is}` : `:root${is}, ${is}`
    const light = decl(t.light), dark = decl(t.dark)
    // a forced scheme: data-hf-scheme="light" | "dark" on any element (a widget sets it on its own host, e.g. <agui-chat>),
    // answered with the scheme of the theme it sits in: on the theme's element itself or anywhere inside it; the default
    // theme also answers a bare attribute (a page without data-hf-theme)
    const forced = (s) => [`${is}[data-hf-scheme="${s}"]`, `${is} [data-hf-scheme="${s}"]`, ...(id === DEFAULT_THEME ? [`[data-hf-scheme="${s}"]`] : [])].join(', ')
    if (t.scheme === 'light' || !Object.keys(t.dark).length) {
      css += block(own, `  color-scheme: light;\n${light}`)
      // a light-only theme stays light whatever scheme an element inside asks for (the cabinet has no dark theme)
      css += block(`${is} [data-hf-scheme]`, `  color-scheme: light;\n${light}`)
      continue
    }
    if (t.scheme === 'dark') { css += block(own, `  color-scheme: dark;\n${dark}`); continue }
    css += block(own, `  color-scheme: light;\n${light}`)
    css += `@media (prefers-color-scheme: dark) {\n` + block(own, `  color-scheme: dark;\n${dark}`).replace(/^/gm, '  ').trimEnd() + `\n}\n`
    css += block(forced('light'), `  color-scheme: light;\n${light}`)
    css += block(forced('dark'), `  color-scheme: dark;\n${dark}`)
  }
  return css
}

// aliases live on the same elements as the theme values, so a themed container re-resolves them
export function compatCss({ base, themes, compat }) {
  let css = HEAD('compat (old names, delete when unused)')
  const baseNames = new Set(base.map((t) => t.name))
  const b = Object.entries(compat.base).map(([old, tok]) => {
    if (!baseNames.has(tok)) throw new Error(`compat ${old}: no base token ${tok}`)
    return `  ${old}: var(--hf-${tok});`
  })
  css += block(':root', b.join('\n'))
  const ids = [DEFAULT_THEME, ...Object.keys(themes).filter((id) => id !== DEFAULT_THEME)]
  for (const id of ids) {
    const t = themes[id], has = new Set([...Object.keys(t.light), ...Object.keys(t.dark)])
    const lines = []
    for (const [old, spec] of Object.entries(compat.theme)) {
      const tok = typeof spec === 'string' ? spec : spec.token
      if (typeof spec === 'object' && spec.themes && !spec.themes.includes(id)) continue
      if (has.has(tok)) lines.push(`  ${old}: var(--hf-${tok});`)
    }
    const is = `[data-hf-theme="${id}"]`
    css += block(id === DEFAULT_THEME ? `:root, ${is}, [data-hf-scheme]` : `:root${is}, ${is}, ${is} [data-hf-scheme]`, lines.join('\n'))
  }
  return css
}

export function iosCss({ base }) {
  const ios = base.filter((t) => t.legacy && t.legacy.startsWith('--ios-'))
  return HEAD('ios measures for the sites (inlined by demo/render.py IOS_CSS, imported by frontend/kit/kit.css)') +
    block(':root', ios.map((t) => `  ${t.legacy}: ${t.value};`).join('\n'))
}

export function tokensJson({ base, themes }) {
  return JSON.stringify({ base: Object.fromEntries(base.map((t) => [t.name, t.value])), themes }, null, 2) + '\n'
}

export function build() {
  const all = load()
  mkdirSync(join(ROOT, 'dist'), { recursive: true })
  const files = { 'tokens.css': tokensCss(all), 'compat.css': compatCss(all), 'ios-tokens.css': iosCss(all), 'tokens.json': tokensJson(all) }
  files['components.js'] = readFileSync(join(ROOT, 'components/hf.js'), 'utf8')  // the web components, one file, no build step
  for (const [f, text] of Object.entries(files)) writeFileSync(join(ROOT, 'dist', f), text)
  return files
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = build()
  for (const [f, t] of Object.entries(files)) console.log(`dist/${f}  ${t.length} B`)
}
